test("spec review packet binds a material artifact hash for a clean session", async () => {
  const target = await project("spec-review");
  const artifact = path.join(target, "_bmad-output", "prd.md");
  await fs.mkdir(path.dirname(artifact), { recursive: true });
  await fs.writeFile(artifact, "# PRD\n\nstatus: review\n");
  const result = run(target, "spec-review-packet.mjs", ["--artifact", artifact, "--lens", "security"]);
  assert.equal(result.status, 0, result.stderr);
  const output = result.stdout.trim();
  const packet = JSON.parse(await fs.readFile(path.join(target, output), "utf8"));
  assert.equal(packet.kind, "spec-review");
  assert.equal(packet.cleanContextRequired, true);
  assert.equal(packet.artifact.sha256.length, 64);
  assert.equal(packet.packetHash.length, 64);
  assert.equal(run(target, "spec-review-packet.mjs", ["verify", output]).status, 0);
  assert.notEqual(run(target, "spec-review-packet.mjs", ["--artifact", artifact, "--lens", "../../escape"]).status, 0);
  const packetFile = path.join(target, output);
  const originalPacket = await fs.readFile(packetFile, "utf8");
  const tamperedPacket = JSON.parse(originalPacket);
  tamperedPacket.lens = "product";
  await fs.writeFile(packetFile, `${JSON.stringify(tamperedPacket, null, 2)}\n`);
  assert.notEqual(run(target, "spec-review-packet.mjs", ["verify", output]).status, 0);
  await fs.writeFile(packetFile, originalPacket);
  await fs.appendFile(artifact, "changed\n");
  assert.notEqual(run(target, "spec-review-packet.mjs", ["verify", output]).status, 0);
});

