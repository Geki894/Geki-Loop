import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { installProject } from "../../src/installer.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const bootstrap = ["core", "planning-bmad", "spec-council", "provisioning", "dashboard"];
async function project(name) {
  const target = await fs.mkdtemp(path.join(os.tmpdir(), `geki-runtime-${name}-`));
  await installProject({ target, requestedModules: bootstrap, tools: ["codex"] });
  return target;
}
const run = (target, script, args = []) => spawnSync(process.execPath, [path.join(target, ".geki", "runtime", script), ...args], { cwd: target, encoding: "utf8" });
async function approveStory(target, id, obligations = []) {
  const file = path.join(target, ".geki", "spec", "stories", `${id}.yaml`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, `id: "${id}"\nstatus: approved\ntestObligations: [${obligations.map((item) => `"${item}"`).join(", ")}]\n`);
  assert.equal(run(target, "contracts.mjs", ["approve", file]).status, 0);
}
async function approveEpic(target, id, stories, obligations = ["github"]) {
  const file = path.join(target, ".geki", "spec", "epics", `${id}.json`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, `${JSON.stringify({ schemaVersion: 1, id: String(id), status: "approved", stories, testObligations: obligations }, null, 2)}\n`);
  assert.equal(run(target, "contracts.mjs", ["approve", file]).status, 0);
}

test("execution requires approved readiness and explicit scope; repair stops at three", async () => {
  const target = await project("state");
  const git = (...args) => spawnSync("git", args, { cwd: target, encoding: "utf8" });
  assert.equal(git("init").status, 0);
  git("config", "user.email", "geki-test@example.invalid");
  git("config", "user.name", "Geki Test");
  git("add", "-A");
  assert.equal(git("commit", "-m", "fixture").status, 0);
  assert.equal(git("branch", "-M", "main").status, 0);
  let result = run(target, "state.mjs", ["start"]);
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /Explicit scope required/);
  const architectureFile = path.join(target, ".geki", "architecture.json");
  const stateFile = path.join(target, ".geki", "state", "current-run.json");
  const architecture = JSON.parse(await fs.readFile(architectureFile, "utf8"));
  architecture.status = "approved";
  await fs.writeFile(architectureFile, `${JSON.stringify(architecture, null, 2)}\n`);
  const state = JSON.parse(await fs.readFile(stateFile, "utf8"));
  state.phase = "ready";
  await fs.writeFile(stateFile, `${JSON.stringify(state, null, 2)}\n`);
  await approveStory(target, "1.1");
  await approveStory(target, "2.1");
  await approveEpic(target, "1", ["1.1"]);
  await approveEpic(target, "2", ["2.1"]);
  result = run(target, "state.mjs", ["start", "--epics", "1,2"]);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(JSON.parse(result.stdout).currentStory, "1.1");
  assert.notEqual(run(target, "state.mjs", ["advance", "--story", "2.1"]).status, 0);
  const active = JSON.parse(await fs.readFile(stateFile, "utf8"));
  active.storyStatus["1.1"] = "integrated";
  await fs.writeFile(stateFile, `${JSON.stringify(active, null, 2)}\n`);
  assert.equal(run(target, "state.mjs", ["advance", "--story", "2.1"]).status, 0);
  assert.notEqual(run(target, "state.mjs", ["advance", "--story", "9.9"]).status, 0);
  for (let attempt = 1; attempt <= 3; attempt++) {
    result = run(target, "state.mjs", ["failure", "--signature", "build:CS1002:Program.cs"]);
    assert.equal(result.status, attempt === 3 ? 2 : 0);
  }
  const current = JSON.parse(await fs.readFile(stateFile, "utf8"));
  assert.equal(current.status, "needs-review");
  assert.equal(current.storyRepairAttempts["2.1"]["build:CS1002:Program.cs"], 3);
  result = run(target, "state.mjs", ["failure", "--signature", "build:CS1002:Program.cs"]);
  assert.equal(result.status, 2);
  result = run(target, "state.mjs", ["failure", "--signature", "different-signature"]);
  assert.equal(result.status, 2);
  const stillThree = JSON.parse(await fs.readFile(stateFile, "utf8"));
  assert.equal(stillThree.storyRepairAttempts["2.1"]["build:CS1002:Program.cs"], 3);
  assert.equal(stillThree.storyRepairAttempts["2.1"]["different-signature"], undefined);
  const reviewFile = path.join(target, ".geki", "evidence", "repair-review.json");
  await fs.mkdir(path.dirname(reviewFile), { recursive: true });
  const reviewedCommit = git("rev-parse", "HEAD").stdout.trim();
  await fs.writeFile(reviewFile, `${JSON.stringify({ kind: "repair-review", outcome: "passed", signature: "wrong", unresolvedHighCritical: 0, reviewerContextId: "reviewer-2", reviewedCommit, approvedStrategy: "inspect compiler diagnostics before changing code" })}\n`);
  assert.notEqual(run(target, "state.mjs", ["failure-clear", "--signature", "build:CS1002:Program.cs", "--evidence", reviewFile]).status, 0);
  await fs.writeFile(reviewFile, `${JSON.stringify({ kind: "repair-review", outcome: "passed", signature: "build:CS1002:Program.cs", unresolvedHighCritical: 0, reviewerContextId: "reviewer-2", reviewedCommit })}\n`);
  assert.notEqual(run(target, "state.mjs", ["failure-clear", "--signature", "build:CS1002:Program.cs", "--evidence", reviewFile]).status, 0);
  await fs.writeFile(reviewFile, `${JSON.stringify({ kind: "repair-review", outcome: "passed", signature: "build:CS1002:Program.cs", unresolvedHighCritical: 0, reviewerContextId: "reviewer-2", reviewedCommit, approvedStrategy: "inspect compiler diagnostics before changing code" })}\n`);
  assert.equal(run(target, "state.mjs", ["failure-clear", "--signature", "build:CS1002:Program.cs", "--evidence", reviewFile]).status, 0);
});

